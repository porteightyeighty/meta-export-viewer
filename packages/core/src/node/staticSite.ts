import crypto from "node:crypto";
import type { Plugin } from "vite";

/**
 * Production build for hosting: the export is read in the visitor's browser, so
 * the page may load its own files and nothing else. `https:` images are only
 * the click-to-load remote images/GIFs in Direct, fetched when the viewer clicks.
 */
const csp = (scriptHashes: string[]) =>
  [
    "default-src 'self'",
    `script-src 'self' ${scriptHashes.map((h) => `'sha256-${h}'`).join(" ")}`.trim(),
    "worker-src 'self'",
    "connect-src 'self'",
    "img-src 'self' blob: data: https:",
    "media-src 'self' blob:",
    "style-src 'self' 'unsafe-inline'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");

/**
 * Build-only plugin: adds a Content-Security-Policy <meta> (works on any host,
 * no server headers needed) and emits `sw.js`, a cache-first service worker
 * over every built file so the site works offline after the first visit.
 */
export function staticSite(): Plugin {
  return {
    name: "meta-static-site",
    apply: "build",
    transformIndexHtml: {
      order: "post",
      handler(html) {
        const hashes = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) =>
          crypto.createHash("sha256").update(m[1]).digest("base64"),
        );
        return html.replace(/<meta charset="UTF-8" \/>/i, (m) => `${m}\n    <meta http-equiv="Content-Security-Policy" content="${csp(hashes)}" />`);
      },
    },
    generateBundle: {
      order: "post",
      handler(_opts, bundle) {
        const files = Object.keys(bundle).sort();
        const version = crypto.createHash("sha256").update(files.join("\n"));
        for (const f of files) {
          const out = bundle[f];
          version.update(out.type === "chunk" ? out.code : out.source);
        }
        this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorker(version.digest("hex").slice(0, 12), ["./", ...files]) });
      },
    },
  };
}

const serviceWorker = (version: string, files: string[]) => `// generated by staticSite(): caches the app so it opens offline
const CACHE = "mev-${version}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) =>
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())),
);
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  // Hash routing: every page is index.html.
  const req = e.request.mode === "navigate" ? new URL("./", self.registration.scope).href : e.request;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`;
